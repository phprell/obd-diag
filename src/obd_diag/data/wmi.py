def manufacturer_for(wmi: str) -> str | None:
    """Hersteller zur WMI (FIN-Stellen 1-3) oder ``None``, wenn nicht in der Tabelle."""
    return MANUFACTURERS.get(wmi.upper())


def country_for(wmi: str) -> str | None:
    """Land nach den ersten zwei Zeichen (ISO-3780-Bereiche) oder ``None``."""
    if len(wmi) < 2:
        return None
    first, second = wmi[0].upper(), wmi[1].upper()
    pos = _ORDER.find(second)
    if pos < 0:
        return None
    for region_first, low, high, country in _REGIONS:
        if region_first == first and _ORDER.index(low) <= pos <= _ORDER.index(high):
            return country
    return None
